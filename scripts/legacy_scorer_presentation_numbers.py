#!/usr/bin/env python
"""Old (as-run) vs corrected (source-faithful) value of every JSON-sourced presentation number; text-sourced numbers are listed for manual review (no PPTX is touched).

    python scripts/legacy_scorer_presentation_numbers.py        # reads committed tables only
Writes docs/presentation/ROUND1_CORRECTED_SLIDE_NUMBERS.{csv,md}.
"""
import json, re
from pathlib import Path
REPO = Path(__file__).resolve().parents[1]
import pandas as pd
rows = json.load(open(REPO / "docs" / "presentation" / "NCDELTA_BASELINE_SLIDE_NUMBERS.json"))
old = json.load(open(REPO / "tables" / "baseline_consolidation" / "summary.json")); new = json.load(open(REPO / "tables" / "legacy_scorer_correction" / "source_faithful" / "baseline_consolidation" / "summary.json"))


def get(d, key):
    for a, b in re.findall(r"\['([^']*)'\]|\[(\d+)\]", key):
        d = d[a] if a != "" else d[int(b)]
    return d


out = []
for r in rows:
    if r["kind"] == "json":
        try:
            vo, vn = get(old, r["key"]), get(new, r["key"])
        except (KeyError, TypeError, IndexError):
            vo, vn = r["value"], None
        same = (vn is not None) and (json.dumps(vo, sort_keys=True) == json.dumps(vn, sort_keys=True))
        status = "UNCHANGED" if same else ("UPDATE" if vn is not None else "REVIEW (key absent in corrected summary)")
        out.append(dict(slide=r["slide"], displayed_old=r["displayed"], meaning=r["meaning"], source=r["key"], old_value=json.dumps(vo, default=float)[:60], corrected_value=json.dumps(vn, default=float)[:60] if vn is not None else "", status=status))
    else:
        out.append(dict(slide=r["slide"], displayed_old=r["displayed"], meaning=r["meaning"], source=f"{r['file'].split('/')[-1]}: {r['key']}", old_value=str(r["value"]), corrected_value="", status="REVIEW (text-sourced; not auto-recomputed)"))
D = pd.DataFrame(out); D.to_csv(REPO / "docs" / "presentation" / "ROUND1_CORRECTED_SLIDE_NUMBERS.csv", index=False)
md = ["# Round-1 slide numbers: as-run vs source-faithful corrected scorer", "",
      "Generated by `scripts/legacy_scorer_presentation_numbers.py` from `tables/baseline_consolidation/summary.json` (HISTORICAL AS-RUN) and `tables/legacy_scorer_correction/source_faithful/baseline_consolidation/summary.json` (CORRECTED). "
      "UPDATE = the value changed; UNCHANGED = identical; REVIEW = text-sourced numbers (from `NCDELTA_FROZEN_WIRECELL_BASELINE.md`), see `ROUND1_SCORER_CORRECTION_PRESENTATION_IMPACT.md` for which of these are scorer-independent.", "",
      f"Counts: {D.status.value_counts().to_dict()}", "", "| slide | displayed (old) | meaning | source | old value | corrected value | status |", "|---|---|---|---|---|---|---|"]
for r in D.itertuples():
    md.append(f"| {r.slide} | {r.displayed_old} | {r.meaning} | `{r.source}` | {r.old_value} | {r.corrected_value} | {r.status} |")
(REPO / "docs" / "presentation" / "ROUND1_CORRECTED_SLIDE_NUMBERS.md").write_text("\n".join(md) + "\n"); print(D.status.value_counts())
