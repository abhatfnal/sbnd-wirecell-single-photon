#!/usr/bin/env python3
"""Render docs/tables/READINESS_PER_INPUT.md from the readiness CSVs and the feature lists (no hand transcription).

Values come from round2/docs/tables/readiness_{full,smoke}_aurora-r2-<sample>.csv (sp_retrain/readiness.py). Inputs that
Xuyang's spec_v1 tables do not carry (the T_kine ones) are taken from the own-builder smoke tables and marked (smoke).
"""
import os, sys

import pandas as pd

ROUND2 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROUND2)
from sp_retrain import features  # noqa: E402

T = os.path.join(ROUND2, 'docs', 'tables')
SAMPLES = ('aurora-r2-ncdr', 'aurora-r2-bnb', 'aurora-r2-nuecc')


def fmt(x, nd=3):
    if pd.isna(x):
        return '-'
    return ('%.' + str(nd) + 'g') % x


def main():
    full = {s: pd.read_csv(os.path.join(T, 'readiness_full_%s.csv' % s)) for s in SAMPLES}
    smoke = {s: pd.read_csv(os.path.join(T, 'readiness_smoke_%s.csv' % s)) for s in SAMPLES}
    out = ['# Per-input readiness of the single-photon ncpi0 / other inputs (generated)', '',
           'Generated by `round2/tools/render_readiness_tables.py` from `readiness_{full,smoke}_*.csv`.',
           '"full" = all aurora-r2 candidates in Xuyang\'s spec_v1 tables (read-only); "(smoke)" = own-builder smoke slices',
           '(ncdr 60 files, bnb 15, nuecc 20) for inputs those tables do not carry. Placeholders dropped. "filled" = shw_sp_filled == 1.',
           'default = modal value on UNFILLED rows (NC-Delta); share = its frequency there; on-filled = fraction of filled rows that',
           'still hold that value. nonfinite = fraction of filled rows with NaN/inf (ncdr / bnb / nuecc).', '']
    for m in ('single_photon_ncpi0', 'single_photon_other'):
        fl = features.load(m)
        out += ['## %s (%d inputs)' % (m, len(fl.inputs)), '',
                '| # | input | CAF branch | type | kind (producer) | in spec_v1 table | default (share) | on-filled | nonfinite ncdr / bnb / nuecc |',
                '|---:|---|---|---|---|---|---|---|---|']
        for i in fl.inputs:
            f0 = full['aurora-r2-ncdr']; row = f0[(f0.model == m) & (f0['index'] == i['index'])].iloc[0]
            src, tag = (full, '') if bool(row.present) else (smoke, ' (smoke)')
            r = src['aurora-r2-ncdr']; r = r[(r.model == m) & (r['index'] == i['index'])].iloc[0]
            nf = ' / '.join(fmt(src[s][(src[s].model == m) & (src[s]['index'] == i['index'])].iloc[0].nonfinite_filled, 2) for s in SAMPLES)
            kind = 'reco' if i['kind'] == 'reco' else 'upstream BDT (%s %s)' % (i['upstream']['producer'], i['upstream']['weights'])
            out.append('| %d | `%s` | `%s` | %s | %s | %s | %s (%s)%s | %s | %s |' % (
                i['index'], i['name'], i['caf_branch'], i['caf_type'], kind, 'yes' if bool(row.present) else 'no',
                fmt(r.unfilled_modal_value), fmt(r.unfilled_modal_share, 2), tag, fmt(r.filled_equal_to_unfilled_modal, 2), nf))
        out.append('')
    path = os.path.join(T, 'READINESS_PER_INPUT.md')
    open(path, 'w').write('\n'.join(out) + '\n')
    print('wrote', path, len(out), 'lines')


if __name__ == '__main__':
    main()
